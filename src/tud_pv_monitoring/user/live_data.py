def last_measurement(cur, module_name: str) -> Optional[tuple]:
    """
    Return the latest measurement for one module as:
        (date_time, voltage, current, temperature_cell)

    The old live_data.py selected every column with SELECT * and then used
    numeric indexes. This version selects only the needed columns by name,
    which is safer and easier to maintain.
    """
    query = f"""
        SELECT {TIME_COL}, {VOLTAGE_COL}, {CURRENT_COL}, {TEMP_COL}
        FROM {TABLE_NAME}
        WHERE {MODULE_COL} = %s
        ORDER BY {TIME_COL} DESC
        LIMIT 1
    """
    cur.execute(query, (module_name,))
    return cur.fetchone()


def to_local_datetime(value, timezone_name: str) -> dt.datetime:
    """Ensure timestamps are timezone-aware for correct matplotlib formatting."""
    timezone = zoneinfo.ZoneInfo(timezone_name)

    if isinstance(value, str):
        value = dt.datetime.fromisoformat(value)

    if value.tzinfo is None:
        return value.replace(tzinfo=timezone)

    return value.astimezone(timezone)


