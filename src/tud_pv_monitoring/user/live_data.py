def update(_frame) -> Sequence:
    """Fetch the newest database row and update all three live plots."""
    global last_seen_time

    measurement = last_measurement(cur, MODULE_NAME)

    if measurement is None:
        print(f"No measurements found for module: {MODULE_NAME}")
        return voltage_line, current_line, temperature_line

    measurement_time, voltage, current, temperature = measurement
    measurement_time = to_local_datetime(measurement_time, TIMEZONE)

    # Avoid plotting the same database row repeatedly between new measurements.
    if measurement_time == last_seen_time:
        return voltage_line, current_line, temperature_line

    last_seen_time = measurement_time
    print(measurement)

    times.append(measurement_time)
    voltages.append(voltage)
    currents.append(current)
    temperatures.append(temperature)

    voltage_line.set_data(times, voltages)
    current_line.set_data(times, currents)
    temperature_line.set_data(times, temperatures)

    for ax in axes:
        ax.relim()
        ax.autoscale_view(scalex=False, scaley=True)

    # Show a scrolling time window once at least one point exists.
    if times:
        axes[-1].set_xlim(times[-1] - WINDOW_DURATION, times[-1])

    return voltage_line, current_line, temperature_line


